import { afterEach, describe, expect, it } from 'vitest';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const generator = resolve(process.cwd(), 'deploy/k3s/resolv-conf.mjs');
// k3s writes this pair itself when the host's resolv.conf has no usable nameserver.
const k3sFallback = 'nameserver 8.8.8.8\nnameserver 2001:4860:4860::8888\n';

const roots: string[] = [];
afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});
function workspace(name: string): string {
  const root = mkdtempSync(join(tmpdir(), `k3s-resolv-${name}-`));
  roots.push(root);
  return root;
}
function write(path: string, body: string): string {
  writeFileSync(path, body);
  return path;
}

// Run the generator exactly as both install paths' units do.
function generate(
  source: string,
  options: { sourcePath?: string; alternate?: string } = {}
): { status: number | null; stdout: string; stderr: string; target: string; sourcePath: string } {
  const root = workspace('generate');
  const sourcePath = options.sourcePath ?? write(join(root, 'resolv.conf'), source);
  const alternate =
    options.alternate === undefined ? null : write(join(root, 'resolved.conf'), options.alternate);
  const target = join(root, 'run/k3s-resolv.conf');
  const result = spawnSync(
    process.execPath,
    [generator, target, sourcePath, ...(alternate ? [alternate] : [])],
    {
      encoding: 'utf8',
      timeout: 10_000,
    }
  );
  return {
    status: result.status,
    stdout: result.stdout,
    stderr: result.stderr,
    target,
    sourcePath,
  };
}

describe('the resolv.conf k3s gives the kubelet and CoreDNS', () => {
  it('keeps the LAN nameserver and drops the link-local one k3s rejects', () => {
    const run = generate(
      [
        '# Generated by dhcpcd',
        'nameserver 192.168.0.30',
        'nameserver fe80::1a2b:c3ff:fe4d:5e6f%ens18',
        'search inside.shady2k.ru',
        'options edns0',
        '',
      ].join('\n')
    );
    expect(run.status, run.stderr).toBe(0);
    expect(run.stdout).toBe('changed\n');
    expect(readFileSync(run.target, 'utf8')).toBe(
      ['nameserver 192.168.0.30', 'search inside.shady2k.ru', ''].join('\n')
    );
  }, 30_000);

  it.each([
    ['192.168.0.30', true],
    ['10.1.2.3', true],
    ['172.16.9.9', true],
    ['8.8.8.8', true],
    ['0.1.2.3', true],
    ['240.1.2.3', true],
    ['2001:db8::53%eth0', false],
    ['169.254.169.254', true],
    ['2001:4860:4860::8888', true],
    ['fd00::1', true],
    ['::ffff:192.168.0.30', true],
    // k3s rejects the whole file when any nameserver is not a global unicast
    // address, so every one of these has to go.
    ['127.0.0.1', false],
    ['127.0.0.53', false],
    ['0.0.0.0', false],
    ['169.254.1.1', false],
    ['224.0.0.1', false],
    ['255.255.255.255', false],
    ['::1', false],
    ['::', false],
    ['fe80::1', false],
    ['fe80::1a2b:c3ff:fe4d:5e6f%ens18', false],
    ['febf::1%eth0', false],
    ['ff02::1', false],
    ['::ffff:127.0.0.1', false],
    ['not-an-address', false],
    ['1.2.3', false],
    ['999.1.1.1', false],
    ['', false],
  ])(
    'keeps %j only when it is usable: %s',
    (address, kept) => {
      const run = generate(['nameserver 203.0.113.7', `nameserver ${address}`, ''].join('\n'));
      expect(run.status, run.stderr).toBe(0);
      const nameservers = readFileSync(run.target, 'utf8')
        .split('\n')
        .filter((line) => line.startsWith('nameserver '))
        .map((line) => line.slice('nameserver '.length));
      expect(nameservers).toEqual(kept ? ['203.0.113.7', address] : ['203.0.113.7']);
    },
    30_000
  );

  it.each([
    [
      'U+0085 (Go whitespace)',
      'nameserver 192.168.0.30\n\u0085nameserver 127.0.0.1\n',
      'nameserver 192.168.0.30\n',
    ],
    [
      'indented LF entry',
      'search lan\n nameserver 127.0.0.1\nnameserver 192.168.0.30\n',
      'nameserver 192.168.0.30\nsearch lan\n',
    ],
    [
      'malformed continuation',
      'nameserver 192.168.0.30\n nameserver\n 127.0.0.1\n',
      'nameserver 192.168.0.30\n',
    ],
    ['embedded CR', 'nameserver 192.168.0.30\rnameserver 127.0.0.1\n', k3sFallback],
    [
      'verbatim tokens',
      '  nameserver   192.168.0.30 # host\noptions ndots:5\n',
      'nameserver 192.168.0.30\n',
    ],
    ['Unicode space', 'nameserver 192.168.0.30\u00a0\n', k3sFallback],
    [
      'overlong search',
      `nameserver 192.168.0.30\nsearch ${'a'.repeat(64)}\n`,
      'nameserver 192.168.0.30\n',
    ],
    [
      'too many domains',
      'nameserver 192.168.0.30\nsearch a b c d e f g\n',
      'nameserver 192.168.0.30\n',
    ],
    [
      'search total limit',
      `nameserver 192.168.0.30\nsearch ${Array(5).fill('a'.repeat(60)).join(' ')}\n`,
      'nameserver 192.168.0.30\n',
    ],
    ['invalid domain', 'nameserver 192.168.0.30\nsearch -bad.lan\n', 'nameserver 192.168.0.30\n'],
  ])(
    'serializes only validated records: %s',
    (_name, input, expected) => {
      const run = generate(input);
      expect(run.status, run.stderr).toBe(0);
      const content = readFileSync(run.target, 'utf8');
      expect(content).toBe(expected);
      // Go Fields includes U+0085, unlike JS \s. Every consumer-visible record
      // must be one of the canonical records above, never copied host bytes.
      expect(content).not.toMatch(/[^\x20-\x7e\n]/);
    },
    30_000
  );

  it("caps nameservers at kubelet's three-server limit in source order", () => {
    const run = generate(
      'nameserver 10.0.0.1\nnameserver 10.0.0.2\nnameserver 10.0.0.3\nnameserver 10.0.0.4\n'
    );
    expect(readFileSync(run.target, 'utf8')).toBe(
      'nameserver 10.0.0.1\nnameserver 10.0.0.2\nnameserver 10.0.0.3\n'
    );
  }, 30_000);

  it('reports unchanged and leaves the file alone when the host did not change', () => {
    const run = generate('nameserver 192.168.0.30\n');
    expect(run.stdout).toBe('changed\n');
    const second = spawnSync(process.execPath, [generator, run.target, run.sourcePath], {
      encoding: 'utf8',
      timeout: 10_000,
    });
    expect(second.status, second.stderr).toBe(0);
    expect(second.stdout).toBe('unchanged\n');
    expect(readFileSync(run.target, 'utf8')).toBe('nameserver 192.168.0.30\n');
  }, 30_000);

  it('falls back to the nameservers k3s itself would write when none is usable', () => {
    const run = generate('nameserver 127.0.0.53\nsearch lan\n');
    expect(run.status, run.stderr).toBe(0);
    expect(readFileSync(run.target, 'utf8')).toBe(`${k3sFallback}search lan\n`);
    const loopbackOnly = generate('nameserver ::1\nnameserver 127.0.0.1\n');
    expect(readFileSync(loopbackOnly.target, 'utf8')).toBe(k3sFallback);
  }, 30_000);

  it("reads systemd-resolved's upstream list when the host file is the stub", () => {
    // Ubuntu and NixOS point /etc/resolv.conf at 127.0.0.53: no pod can use it,
    // and leaving it out of the search for a usable resolver would hide the LAN.
    const run = generate('nameserver 127.0.0.53\nsearch lan\n', {
      alternate: 'nameserver 192.168.0.30\nsearch inside.shady2k.ru\n',
    });
    expect(run.status, run.stderr).toBe(0);
    expect(run.stdout).toBe('changed\n');
    expect(readFileSync(run.target, 'utf8')).toBe(
      'nameserver 192.168.0.30\nsearch inside.shady2k.ru\n'
    );
  }, 30_000);

  it('prefers the host file k3s would accept over the resolver stub', () => {
    const run = generate('nameserver 192.168.0.30\nsearch lan\n', {
      alternate: 'nameserver 203.0.113.7\n',
    });
    expect(readFileSync(run.target, 'utf8')).toBe('nameserver 192.168.0.30\nsearch lan\n');
  }, 30_000);

  it('falls back and says so when the host has no resolv.conf to read', () => {
    const root = workspace('missing');
    const absent = join(root, 'absent/resolv.conf');
    const run = generate('', { sourcePath: absent });
    expect(run.status, run.stderr).toBe(0);
    expect(run.stdout).toBe('changed\n');
    expect(readFileSync(run.target, 'utf8')).toBe(k3sFallback);
    expect(run.stderr).toContain(absent);
  }, 30_000);
});
