import { afterEach, describe, expect, it } from 'vitest';
import {
  chmodSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const generator = resolve(process.cwd(), 'deploy/k3s/resolv-conf.mjs');
const orchestrator = resolve(process.cwd(), 'deploy/k3s/k3s-resolv.sh');
// k3s writes this pair itself when the host's resolv.conf has no usable nameserver.
const k3sFallback = 'nameserver 8.8.8.8\nnameserver 2001:4860:4860::8888\n';

const roots: string[] = [];
afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});
function workspace(name: string): string {
  const root = mkdtempSync(join(tmpdir(), `k3s-resolv-${name}-`));
  roots.push(root);
  return root;
}
function write(path: string, body: string): string {
  writeFileSync(path, body);
  return path;
}

// Run the generator exactly as both install paths' units do.
function generate(
  source: string,
  options: { sourcePath?: string; alternate?: string } = {}
): { status: number | null; stdout: string; stderr: string; target: string; sourcePath: string } {
  const root = workspace('generate');
  const sourcePath = options.sourcePath ?? write(join(root, 'resolv.conf'), source);
  const alternate = options.alternate === undefined ? null : write(join(root, 'resolved.conf'), options.alternate);
  const target = join(root, 'run/k3s-resolv.conf');
  const result = spawnSync(process.execPath, [generator, target, sourcePath, ...(alternate ? [alternate] : [])], {
    encoding: 'utf8',
    timeout: 10_000,
  }, 30_000);
  return {
    status: result.status,
    stdout: result.stdout,
    stderr: result.stderr,
    target,
    sourcePath,
  };
}

describe('the resolv.conf k3s gives the kubelet and CoreDNS', () => {
  it('keeps the LAN nameserver and drops the link-local one k3s rejects', () => {
    const run = generate(
      [
        '# Generated by dhcpcd',
        'nameserver 192.168.0.30',
        'nameserver fe80::1a2b:c3ff:fe4d:5e6f%ens18',
        'search inside.shady2k.ru',
        'options edns0',
        '',
      ].join('\n')
    );
    expect(run.status, run.stderr).toBe(0);
    expect(run.stdout).toBe('changed\n');
    expect(readFileSync(run.target, 'utf8')).toBe(
      [
        '# Generated by dhcpcd',
        'nameserver 192.168.0.30',
        'search inside.shady2k.ru',
        'options edns0',
        '',
      ].join('\n')
    );
  }, 30_000);

  it.each([
    ['192.168.0.30', true],
    ['10.1.2.3', true],
    ['172.16.9.9', true],
    ['8.8.8.8', true],
    ['169.254.169.254', true],
    ['2001:4860:4860::8888', true],
    ['fd00::1', true],
    ['::ffff:192.168.0.30', true],
    // k3s rejects the whole file when any nameserver is not a global unicast
    // address, so every one of these has to go.
    ['127.0.0.1', false],
    ['127.0.0.53', false],
    ['0.0.0.0', false],
    ['169.254.1.1', false],
    ['224.0.0.1', false],
    ['255.255.255.255', false],
    ['::1', false],
    ['::', false],
    ['fe80::1', false],
    ['fe80::1a2b:c3ff:fe4d:5e6f%ens18', false],
    ['febf::1%eth0', false],
    ['ff02::1', false],
    ['::ffff:127.0.0.1', false],
    ['not-an-address', false],
    ['1.2.3', false],
    ['999.1.1.1', false],
    ['', false],
  ])('keeps %j only when it is usable: %s', (address, kept) => {
    const run = generate(['nameserver 203.0.113.7', `nameserver ${address}`, ''].join('\n'));
    expect(run.status, run.stderr).toBe(0);
    const nameservers = readFileSync(run.target, 'utf8')
      .split('\n')
      .filter((line) => line.startsWith('nameserver '))
      .map((line) => line.slice('nameserver '.length));
    expect(nameservers).toEqual(kept ? ['203.0.113.7', address] : ['203.0.113.7']);
  }, 30_000);

  it('reports unchanged and leaves the file alone when the host did not change', () => {
    const run = generate('nameserver 192.168.0.30\n');
    expect(run.stdout).toBe('changed\n');
    const second = spawnSync(process.execPath, [generator, run.target, run.sourcePath], {
      encoding: 'utf8',
      timeout: 10_000,
    });
    expect(second.status, second.stderr).toBe(0);
    expect(second.stdout).toBe('unchanged\n');
    expect(readFileSync(run.target, 'utf8')).toBe('nameserver 192.168.0.30\n');
  }, 30_000);

  it('falls back to the nameservers k3s itself would write when none is usable', () => {
    const run = generate('nameserver 127.0.0.53\nsearch lan\n');
    expect(run.status, run.stderr).toBe(0);
    expect(readFileSync(run.target, 'utf8')).toBe(`search lan\n${k3sFallback}`);
    const loopbackOnly = generate('nameserver ::1\nnameserver 127.0.0.1\n');
    expect(readFileSync(loopbackOnly.target, 'utf8')).toBe(k3sFallback);
  }, 30_000);

  it('reads systemd-resolved\'s upstream list when the host file is the stub', () => {
    // Ubuntu and NixOS point /etc/resolv.conf at 127.0.0.53: no pod can use it,
    // and leaving it out of the search for a usable resolver would hide the LAN.
    const run = generate('nameserver 127.0.0.53\nsearch lan\n', {
      alternate: 'nameserver 192.168.0.30\nsearch inside.shady2k.ru\n',
    });
    expect(run.status, run.stderr).toBe(0);
    expect(run.stdout).toBe('changed\n');
    expect(readFileSync(run.target, 'utf8')).toBe('nameserver 192.168.0.30\nsearch inside.shady2k.ru\n');
  }, 30_000);

  it('prefers the host file k3s would accept over the resolver stub', () => {
    const run = generate('nameserver 192.168.0.30\nsearch lan\n', {
      alternate: 'nameserver 203.0.113.7\n',
    });
    expect(readFileSync(run.target, 'utf8')).toBe('nameserver 192.168.0.30\nsearch lan\n');
  }, 30_000);

  it('falls back and says so when the host has no resolv.conf to read', () => {
    const root = workspace('missing');
    const absent = join(root, 'absent/resolv.conf');
    const run = generate('', { sourcePath: absent });
    expect(run.status, run.stderr).toBe(0);
    expect(run.stdout).toBe('changed\n');
    expect(readFileSync(run.target, 'utf8')).toBe(k3sFallback);
    expect(run.stderr).toContain(absent);
  }, 30_000);
});

// The unit body both install paths run: write the file, then make the pods that
// hold the old nameservers take the new ones. CoreDNS runs with dnsPolicy
// Default, so it forwards to the nameservers copied into it when it was created.
const kubectlDelete =
  'k3s kubectl --kubeconfig /etc/rancher/k3s/k3s.yaml -n kube-system delete pod -l k8s-app=kube-dns --wait=false';
describe('applying the regenerated resolv.conf', () => {
  function fixture(source: string, options: { k3sActive?: boolean; kubectlStatus?: number } = {}) {
    const root = workspace('apply');
    const bin = join(root, 'bin');
    mkdirSync(bin);
    const calls = write(join(root, 'calls.log'), '');
    write(
      join(bin, 'systemctl'),
      `#!/bin/sh
printf 'systemctl %s\\n' "$*" >> "$CALLS"
case "$*" in
  *is-active*) [ "$K3S_ACTIVE" = 1 ] && exit 0 || exit 3 ;;
esac
exit 0
`
    );
    write(
      join(bin, 'k3s'),
      `#!/bin/sh
printf 'k3s %s\\n' "$*" >> "$CALLS"
exit "\${KUBECTL_STATUS:-0}"
`
    );
    chmodSync(join(bin, 'systemctl'), 0o755);
    chmodSync(join(bin, 'k3s'), 0o755);
    const sourcePath = write(join(root, 'resolv.conf'), source);
    const target = join(root, 'run/k3s-resolv.conf');
    const env = {
      ...process.env,
      PATH: `${bin}:${process.env.PATH}`,
      CALLS: calls,
      K3S_ACTIVE: options.k3sActive === false ? '0' : '1',
      KUBECTL_STATUS: String(options.kubectlStatus ?? 0),
    };
    const run = () => {
      const read = () => readFileSync(calls, 'utf8');
      const before = read().length;
      const result = spawnSync('sh', [orchestrator, generator, target, sourcePath], {
        encoding: 'utf8',
        timeout: 10_000,
        env,
      });
      return { status: result.status, stderr: result.stderr, calls: read().slice(before) };
    };
    return { run, target };
  }

  it('recreates the CoreDNS pods that hold the old nameservers', () => {
    const host = fixture('nameserver 192.168.0.30\nnameserver fe80::1%ens18\n');
    const run = host.run();
    expect(run.status, run.stderr).toBe(0);
    expect(readFileSync(host.target, 'utf8')).toBe('nameserver 192.168.0.30\n');
    expect(run.calls).toBe(`systemctl is-active --quiet k3s.service\n${kubectlDelete}\n`);
  }, 30_000);

  it('leaves the running pods alone when the host did not change', () => {
    const host = fixture('nameserver 192.168.0.30\n');
    const first = host.run();
    expect(first.status, first.stderr).toBe(0);
    expect(first.calls).toBe(`systemctl is-active --quiet k3s.service\n${kubectlDelete}\n`);
    const second = host.run();
    expect(second.status, second.stderr).toBe(0);
    // Nothing changed, so nothing is regenerated and no pod is touched.
    expect(second.calls).toBe('');
  }, 30_000);

  it('does not reach for a cluster that is not running', () => {
    const host = fixture('nameserver 192.168.0.30\n', { k3sActive: false });
    const run = host.run();
    expect(run.status, run.stderr).toBe(0);
    expect(readFileSync(host.target, 'utf8')).toBe('nameserver 192.168.0.30\n');
    expect(run.calls).toBe('systemctl is-active --quiet k3s.service\n');
  }, 30_000);

  it('reports a CoreDNS recreation that failed', () => {
    const host = fixture('nameserver 192.168.0.30\n', { kubectlStatus: 1 });
    const run = host.run();
    expect(run.status).not.toBe(0);
    // The file is written before the pods are touched, so nothing is lost.
    expect(readFileSync(host.target, 'utf8')).toBe('nameserver 192.168.0.30\n');
  }, 30_000);
});
